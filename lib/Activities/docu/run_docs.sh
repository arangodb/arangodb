#!/usr/bin/env bash
# Driver for find-activity-subclasses. Walks the project's
# compile_commands.json in parallel, emits one markdown fragment per
# Activity subclass, then concatenates the fragments into Activities.md.
#
# Args:
#   $1  path to find-activity-subclasses binary
#   $2  directory containing compile_commands.json (build-presets/<preset>)
#   $3  output directory (where generated/Activities.md will land)
#   $4  project root (filter to source files under this path)

set -euo pipefail

BIN="${1:?binary path required}"
CC_DB="${2:?compile_commands.json directory required}"
OUT="${3:?output directory required}"
PROJECT_ROOT="${4:?project root required}"

if [[ ! -x "$BIN" ]]; then
    echo "binary not found or not executable: $BIN" >&2
    exit 1
fi
if [[ ! -f "$CC_DB/compile_commands.json" ]]; then
    echo "no compile_commands.json under: $CC_DB" >&2
    exit 1
fi

PROJECT_ROOT="$(cd "$PROJECT_ROOT" && pwd)"

FRAG="$OUT/.fragments"
mkdir -p "$FRAG"
# Wipe stale fragments so the merge step is fully deterministic.
rm -f "$FRAG"/*.md

PARALLEL="${ACTIVITY_DOCS_PARALLEL:-8}"
BATCH="${ACTIVITY_DOCS_BATCH:-50}"

# Only TUs under arangod/ and lib/ can contain Activity subclasses; scoping the
# file list keeps the AST walk fast even on a full compile_commands.json.
# Some entries in compile_commands.json point to generated sources that may
# not exist on disk yet (Aql/grammar.cpp, etc.) — drop those before running.
FILELIST="$(mktemp)"
trap 'rm -f "$FILELIST"' EXIT
jq -r --arg arangod "$PROJECT_ROOT/arangod/" --arg lib "$PROJECT_ROOT/lib/" \
    '.[] | select(.file | startswith($arangod) or startswith($lib)) | .file' \
    "$CC_DB/compile_commands.json" \
    | sort -u \
    | while IFS= read -r f; do
        [[ -f "$f" ]] && printf '%s\n' "$f"
    done > "$FILELIST"

echo "scanning $(wc -l < "$FILELIST") translation units..."

# xargs returns 123 if any invocation exited 1-125. ClangTool exits non-zero
# for legitimate per-TU parse errors that don't affect the rest of the run, so
# treat anything below 126 as a soft failure and continue to the merge step.
set +e
xargs -a "$FILELIST" -n "$BATCH" -P "$PARALLEL" \
    "$BIN" -p "$CC_DB" --output-dir "$FRAG" 2>&1 \
    | grep -vE "^\[[0-9]+/[0-9]+\] Processing file " || true
xargs_status=${PIPESTATUS[0]}
set -e
if (( xargs_status >= 126 )); then
    echo "xargs hard-failed with $xargs_status" >&2
    exit "$xargs_status"
fi
if (( xargs_status != 0 )); then
    echo "xargs reported partial per-TU failures (exit $xargs_status); continuing." >&2
fi

OUTFILE="$OUT/Activities.md"
{
    echo "# Activities"
    echo
    echo "_Auto-generated by \`cmake --build <build> --target activity-docs\`. Do not edit by hand._"
    echo
    echo "Each section below describes one concrete subclass of"
    echo "\`arangodb::activities::Activity\`. The Snapshot envelope is fixed by"
    echo "\`GuardedActivity::Snapshot\`; the Data fields are extracted from the"
    echo "subclass's \`Data\` template argument."
    echo
    if compgen -G "$FRAG/*.md" > /dev/null; then
        for f in $(ls "$FRAG"/*.md | LC_ALL=C sort); do
            cat "$f"
            echo
        done
    else
        echo "_No Activity subclasses found._"
    fi
} > "$OUTFILE"

rm -rf "$FRAG"

echo "wrote $OUTFILE"
