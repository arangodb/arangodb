function normalizeSuiteFilter (value) {
  const one = (item) => (typeof item === 'number')
    ? String(item).padStart(3, '0')
    : String(item);
  let filter = Array.isArray(value) ? value.map(one).join(',') : one(value);
  if (!filter.includes(',')) {
    filter = `${filter},${filter}`;
  }
  return filter;
}

