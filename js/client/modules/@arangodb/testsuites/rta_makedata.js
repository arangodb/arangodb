function makeDataWrapper (options) {
  let stoppedDbServerInstance = {};
  if (options.hasOwnProperty('test') && (typeof (options.test) !== 'undefined')) {
    if (!options['makedataArgs']) {
      options['makedataArgs'] = {};
    }
    options['makedataArgs']['test'] = normalizeSuiteFilter(options.test);
  }

  let messages = [
    "initially create the test data",
    "revalidate the test data for the first time",
    "obstruct system, and check whether the data is still valid",
    "waiting for the SUT to settle down",
    "cleaning up test data generated by makedata"
  ];
  let testCases = [
    "MakeData",
    "CheckData",
    "waitData",
    "ClearData"
  ];
  class rtaMakedataRunner extends testRunnerBase {
    constructor(options, testname, ...optionalArgs) {
      super(options, testname, ...optionalArgs);
      this.info = "runRtaInArangosh";
      if (isEnterprise()) {
        this.serverOptions["arangosearch.columns-cache-limit"] = "5000";
      }
      this.continueTesting = true;
      if (this.options.isCov) {
        this.options.oneTestTimeout = this.options.oneTestTimeout * 4;
      }
      if (this.options.rbac) {
        Object.assign(this.serverOptions, tu.testServerAuthInfo);
        this.serverOptions['network.compression-method'] = 'none';
      }
    }
    filter(te, filtered) {
      return true;
    }

    postStart() {
      if (!this.options.cluster) {
        this.instanceManager.setPassvoid();
      }
      return {
        message: '',
        state: true,
      };
    }

    checkSutCleannessBefore(te) {
      if (this.continueTesting) {
        return super.checkSutCleannessBefore(te);
      }
      return false;
    }
    checkSutCleannessAfter(te) {
      if (this.continueTesting) {
        return super.checkSutCleannessAfter(te);
      }
      return false;
    }

    createDump() {
      this.dumpConfig = ct.createBaseConfig('dump', this.options, this.instanceManager);
      this.dumpConfig.setOutputDirectory('dump');
      this.dumpConfig.setIncludeSystem(true);
      this.dumpConfig.setAllDatabases();
      return ct.run.arangoDumpRestoreWithConfig(this.dumpConfig, this.options, this.instanceManager.rootDir, this.options.coreCheck);

    }
    restoreDump() {
      this.restoreConfig = ct.createBaseConfig('restore', this.options, this.instanceManager);
      this.restoreConfig.setInputDirectory('dump', true);
      this.restoreConfig.setIncludeSystem(true);
      this.restoreConfig.setAllDatabases();
      return ct.run.arangoDumpRestoreWithConfig(this.restoreConfig, this.options, this.instanceManager.rootDir, this.options.coreCheck);
    }

    // //////////////////////////////////////////////////////////////////////
    // / Drive the RBAC scenario matrix (tests/api/rbac/rta) against the SUT.
    // / Runs only when --rbac was given a URL.
    // //////////////////////////////////////////////////////////////////////
    rbacRunnerArgs() {
      const secretFile = fs.join(this.instanceManager.rootDir, 'rta_rbac_jwt_secret');
      fs.write(secretFile, this.instanceManager.JWT);
      return [
        fs.join(this.options.rtaRbacDir, 'run_scenarios.py'),
        '--management', this.options.rbac,
        '--integration', this.options.rbac,
        '--jwt-secret-file', secretFile,
        '--external-sidecar',
      ];
    }

    bootstrapRbacUser(remove) {
      if (typeof this.options.rbac !== 'string') {
        return true;
      }
      const flag = remove ? '--remove-bootstrap-user' : '--bootstrap-user';
      const argv = this.rbacRunnerArgs().concat([flag, this.options.username]);
      const rc = executeExternalAndWait('python3', argv);
      if (rc.exit !== 0 && !remove) {
        print(`${RED}${(new Date()).toISOString()} could not give ` +
              `'${this.options.username}' an RBAC binding; the workload cannot ` +
              `run against a deny-by-default sidecar without one${RESET}`);
        return false;
      }
      return true;
    }

    runRbacScenarios(res) {
      const whichRTA = 'rta_RbacScenarios';
      res[whichRTA] = {'status': true, 'message': '', 'duration': 0.0};
      if (typeof this.options.rbac !== 'string') {
        res[whichRTA].message =
          'skipped: --rbac was not given a sidecar URL, so there is no ' +
          'management API to seed scenarios through';
        print(`${CYAN}${(new Date()).toISOString()} RBAC scenarios skipped: ` +
              `--rbac needs a real sidecar URL${RESET}`);
        return;
      }

      const runner = fs.join(this.options.rtaRbacDir, 'run_scenarios.py');
      if (!fs.exists(runner)) {
        res[whichRTA].status = false;
        res[whichRTA].message = `RBAC scenario runner not found: ${runner}`;
        res.status = false;
        res.failed += 1;
        return;
      }

      const argv = this.rbacRunnerArgs().concat([
        '--endpoint', this.instanceManager.findEndpoint(),
        '--arangosh', pu.ARANGOSH_BIN,
        '--rta', this.options.rtasource,
      ]);
      if (this.options.hasOwnProperty('test') && (typeof (this.options.test) !== 'undefined')) {
        // Same filter the workload phases ran, normalised the same way.
        argv.push('--test', normalizeSuiteFilter(this.options.test));
      }

      print(`\n${(new Date()).toISOString()}${GREEN}[============] RBAC scenarios: ` +
            `${argv.join(' ')}${RESET}`);
      const start = time();
      const rc = executeExternalAndWait('python3', argv);
      res[whichRTA].duration = time() - start;
      res.total += 1;
      res.duration += res[whichRTA].duration;

      if (rc.exit !== 0) {
        res[whichRTA].status = false;
        res[whichRTA].failed = 1;
        res[whichRTA].message =
          `RBAC scenario matrix reported failures (exit ${rc.exit}); ` +
          `see the output above for the per-step table`;
        res.status = false;
        res.failed += 1;
      }
    }

    runMakeData(moreargv, file, whichRTA, count, testCount, launch, res) {
      let logFile = fs.join(fs.getTempPath(), `rta_out_${count}_${launch}.log`);
      require('internal').env.INSTANCEINFO = JSON.stringify(this.instanceManager.getStructure());
      let rc;
      try {
        rc = ct.run.rtaMakedata(this.options, this.instanceManager, testCount, messages[count-1], logFile, moreargv);
      } catch (ex) {
        print(`${RED}$(Date()} caught exception: ${ex} while ${messages[count-1]} ${ex} - ${ex.stack}${RESET}`);
        throw ex;
      }
      res[whichRTA] = rc;
      if (!rc.status) {
        this.continueTesting = false;
        res[whichRTA].message += file + ':\n' + ct.run.readRtaErrorLog(logFile);
        res.status = false;
        res.failed += 1;
      } else {
        fs.remove(logFile);
      }
      return rc;
    }

    runOneTest(file) {
      this.options.rtaNegFilter = "";
      if (this.options.skipServerJS) {
        // TODO: QA-703
        this.options.rtaNegFilter = "070,071,801,550,900,960";
      }
      if (!this.continueTesting) {
        return {
          'forceTerminate': true,
          'message': `skipped due to previous failure`,
          'failed': 1,
          'status': false,
          'duration': 0.0
        };
      }
      let res = {'total':0, 'duration':0.0, 'status':true, message: '', 'failed': 0};
      if (!this.bootstrapRbacUser(false)) {
        return {
          'message': 'could not bootstrap the RBAC binding for the workload user',
          'failed': 1, 'status': false, 'duration': 0.0
        };
      }
      let count = 0;
      let counters = { nonAgenciesCount: 1};
      [
        0, // makedata
        1, // checkdata
        1, // checkdata (with resillience test - instances stopped)
        3  // clear data
      ].forEach(testCount => {
        let moreargv = [];
        count += 1;
        let whichRTA = `rta_${testCases[testCount]}_${count}`;
        res[whichRTA] = { 'status': true, 'message': ''};
        if (this.options.cluster) {
          if (count === 2) {
            let rc = this.runMakeData(moreargv, file, whichRTA, 2, testCount, 0, res);
            if (!rc.status) {
              this.continueTesting = false;
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `SUT did not get in sync ${rc}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
            rc = ct.run.rtaWaitShardsInSync(this.options, this.instanceManager);
            if (!rc.status) {
              this.continueTesting = false;
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `shards would not get in sync ${rc}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
          }
          if (count === 2) {
            let clientInstances = [];
            try {
              if (this.options.oldSource !== undefined) {
                print("switching binary set");
                pu.switchBinarySet(1);
              }
              this.instanceManager.upgradeCycleInstance(false, {
                dbserverBefore: function() {
                },
                dbserverAfter: function() {
                }
              });
            } catch(e) {
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `upgradeCycle failed by: ${e.message}\n${e.stack}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
          }
          else if (count === 3) {
            this.instanceManager.arangods.forEach(function (oneInstance, i) {
              if (oneInstance.isRole(inst.instanceRole.dbServer)) {
                stoppedDbServerInstance = oneInstance;
              }
            });
            print('stopping dbserver ' + stoppedDbServerInstance.name +
                  ' ID: ' + stoppedDbServerInstance.id +JSON.stringify( stoppedDbServerInstance.getStructure()));
            try {
              this.instanceManager.resignLeaderShip(stoppedDbServerInstance);
            } catch(e) {
              this.continueTesting = false;
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `resigning leadership failed by: ${e.message}\n${e.stack}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
            stoppedDbServerInstance.shutDownOneInstance(counters, false, 10);
            stoppedDbServerInstance.waitForExit();
            moreargv = [ '--disabledDbserverUUID', stoppedDbServerInstance.id];
            if (this.options.replicationVersion === 2 || this.options.replicationVersion === "2") {
              this.instanceManager.removeServerFromAgency(stoppedDbServerInstance.id);
            }
            let rc = this.runMakeData(moreargv, file, whichRTA, 2, 2, 0, res);
            if (!rc.status) {
              this.continueTesting = false;
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `SUT did not get in sync ${rc}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
          }
        } else {
          if (count === 2) {
            this.createDump();
            this.restoreDump();
            let rc = this.runMakeData(moreargv, file, whichRTA, 2, 2, 0, res);
            if (!rc.status) {
              this.continueTesting = false;
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `SUT did not get in sync ${rc}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
          } else if (count === 3) {
            try {
              if (this.options.oldSource !== undefined) {
                print("switching binary set");
                pu.switchBinarySet(1);
              }
              this.instanceManager.upgradeCycleInstance(false, {});
              this.restoreDump();
              let rc = this.runMakeData(moreargv, file, whichRTA, 2, 2, 0, res);
              if (!rc.status) {
                this.continueTesting = false;
                res.status = false;
                res.failed += 1;
                res[whichRTA] = {
                  'forceTerminate': true,
                  'message': `SUT did not get in sync ${rc}`,
                  'failed': 1,
                  'status': false,
                  'duration': 0.0
                };
                return;
              }
            } catch(e) {
              res.status = false;
              res.failed += 1;
              res[whichRTA] = {
                'forceTerminate': true,
                'message': `upgradeCycle failed by: ${e.message}\n${e.stack}`,
                'failed': 1,
                'status': false,
                'duration': 0.0
              };
              return;
            }
          }
        }

        let rc = this.runMakeData(moreargv, file, whichRTA, count, testCount, 0, res);

        res.total++;
        res.duration += rc.duration;
        if (this.options.cluster) {
          if (count === 3) {
            print('relaunching dbserver');
            stoppedDbServerInstance.restartOneInstance({});
          }
        }
      });
      // The scenario matrix runs last: it needs a live SUT, and it seeds and
      // tears down its own databases, so it must not disturb the phases above.
      if (this.options.rbac && this.continueTesting) {
        this.runRbacScenarios(res);
      }
      this.bootstrapRbacUser(true);
      return res;
    }
  }
  if (!options.rtaRbacDir) {
    options.rtaRbacDir = fs.join(fs.makeAbsolute('.'), 'tests', 'api', 'rbac', 'rta');
  }
  let localOptions = Object.assign({}, options, tu.testServerAuthInfo);
  if (localOptions.oldSource !== undefined) {
    localOptions.skipServerJS = false;
  }
  if (localOptions.cluster) {
    if (localOptions.dbServers < 3) {
      localOptions.dbServers = 3;
    }
    localOptions.password = "cluster";
  } else {
    localOptions.password = "single";
  }
  localOptions.extraArgs['vector-index'] = true;

  if (!localOptions.isSan) {
    // don't have default values if non instrumented arangosh.
    ["TSAN_OPTIONS", "UBSAN_OPTIONS", "LSAN_OPTIONS", "ASAN_OPTIONS"].forEach(varname => {
      delete(process.env[varname]);
    });
  }
  SetGlobalExecutionDeadlineTo(localOptions.oneTestTimeout);
  let rc = new rtaMakedataRunner(localOptions, 'rta_makedata_test').run(['rta']);
  let timeout = SetGlobalExecutionDeadlineTo(0.0);
  options.cleanup = options.cleanup && localOptions.cleanup && rc.status;
  if (timeout) {
    return {
      failed: 1,
      timeout: true,
      forceTerminate: true,
      status: false,
      message: `test aborted due to >>${require('internal').getDeadlineReasonString()}<<. Original test status: ${JSON.stringify(rc)}`,
    };
  }
  return rc;
}


exports.setup = function (testFns, opts, fnDocs, optionsDoc, allTestPaths) {
  Object.assign(allTestPaths, testPaths);
  testFns['rta_makedata'] = makeDataWrapper;
  tu.CopyIntoObject(fnDocs, {
    'rta_makedata': 'Release Testautomation Makedata / Checkdata framework'
  });
};
